const (
	addedHunk = "--- /dev/null\n+++ b/new.go\n@@ -0,0 +1 @@\n"
	sourcePkg = "package main\n"
	bare      = "bare //nolint directive"
	all       = "//nolint suppresses all linters"
	funlen    = `//nolint suppresses guarded linter "funlen"`
	generated = "new Go generated-code header"
	passed    = "Lint directives passed: 0 violations.\n"
	failed    = "Lint directives failed. Violations: 1.\n"
	guardFlag = "--guarded=funlen"
	rootFlag  = "--root"
	errcheck  = `//nolint suppresses guarded linter "errcheck"`
	ignored   = "new Go build constraint mentions ignore"
	lineRule  = "new Go line directive"
)

func TestDirectives(t *testing.T) {
	t.Parallel()
	for _, tc := range []struct {
		name, line, reason string
		allowGenerated     bool
	}{
		{name: "bare", line: "//nolint", reason: bare},
		{name: "bare with explanation", line: "//nolint // reason", reason: bare},
		{name: "all", line: "//nolint:all", reason: all},
		{name: "all in list", line: "//nolint:gosec, ALL // reason", reason: all},
		{name: "guarded", line: "//nolint:funlen", reason: funlen},
		{name: "mixed case", line: "/// NoLiNt:FuNlEn", reason: funlen},
		{name: "guarded in list", line: "//nolint:gosec, funlen, unused // reason", reason: funlen},
		{name: "embedded carriage return", line: "//nolint:fun\rlen", reason: funlen},
		{name: "unguarded with reason", line: "//nolint:gosec // reason"},
		{name: "guarded with prose", line: "//nolint:errcheck -- why", reason: errcheck},
		{name: "guarded with period", line: "//nolint:errcheck.", reason: errcheck},
		{name: "guarded with parentheses", line: "//nolint:errcheck(x)", reason: errcheck},
		{name: "guarded with slash", line: "//nolint:errcheck/x", reason: errcheck},
		{name: "longer linter name", line: "//nolint:errcheck-other"},
		{name: "not a directive", line: "//nolinting:funlen"},
		{name: "generated header", line: "// Code generated by a tool. DO NOT EDIT.", reason: generated},
		{name: "BOM before header", line: "\ufeff// Code generated by a tool. DO NOT EDIT.", reason: generated},
		{name: "block generated header", line: "/* Code generated by x DO NOT EDIT. */", reason: generated},
		{name: "lowercase generated header", line: "// code generated by x", reason: generated},
		{name: "allowed header", line: "// Code generated by a tool. DO NOT EDIT.", allowGenerated: true},
		{name: "lax code generated", line: "// this CODE GENERATED file", reason: generated},
		{name: "lax do not edit", line: "// please do not edit this", reason: generated},
		{name: "lax autogenerated file", line: "// AUTOGENERATED FILE", reason: generated},
		{name: "lax swagger", line: "/* * Generated by: Swagger Codegen tool */", reason: generated},
		{name: "allow-generated still checks nolint", line: "//nolint", reason: bare, allowGenerated: true},
		{name: "ignore build tag", line: "//go:build linux && ignore", reason: ignored},
		{name: "ignore legacy build tag", line: "// +build ignore", reason: ignored},
		{name: "different build tag", line: "//go:build ignore_test"},
		{name: "line directive", line: "//line x.go:40", reason: lineRule},
		{name: "block line directive", line: "/*line x.go:40*/", reason: lineRule},
	} {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			root := t.TempDir()
			fixtureFile(t, root, "new.go", tc.line+"\n"+sourcePkg)
			args := []string{rootFlag, root, "--guarded", "cyclop, FunLen, errcheck"}
			if tc.allowGenerated {
				args = append(args, "--allow-generated")
			}
			want, wantCode := passed, 0
			if tc.reason != "" {
				want, wantCode = `"new.go" 1: `+tc.reason+"\n"+failed, 1
			}
			assertDirectives(
				t,
				directiveTest{args: args, diff: addedHunk + "+" + tc.line + "\n"},
				want,
				wantCode,
			)
		})
	}
}

func TestDirectiveNewModules(t *testing.T) {
	t.Parallel()
	for _, tc := range []struct{ name, file, patch, want string }{
		{"nested module", "nested/go.mod", "--- /dev/null\n+++ b/nested/go.mod\n@@ -0,0 +1 @@\n+module m\n", failed},
		{"empty workspace", "sub/go.work", "diff --git a/sub/go.work b/sub/go.work\nnew file mode 100644\n", failed},
		{"existing module", "go.mod", "--- a/go.mod\n+++ b/go.mod\n@@ -1 +1 @@\n-go 1.26.0\n+go 1.25.0\n", passed},
	} {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			input := directiveTest{args: []string{rootFlag, t.TempDir(), guardFlag}, diff: tc.patch}
			if tc.want == failed {
				want := `"` + tc.file + `" 1: new Go module or workspace file` + "\n" + failed
				assertDirectives(t, input, want, 1)
			} else {
				assertDirectives(t, input, passed, 0)
			}
			input.args = append(input.args, "--allow-new-modules")
			assertDirectives(t, input, passed, 0)
		})
	}
}

func TestDirectiveHunks(t *testing.T) {
	t.Parallel()
	const patch = "diff --git a/binary.go b/binary.go\nBinary files a/binary.go and b/binary.go differ\n" +
		"diff --git a/one.go b/one.go\nindex ba7..f01 100644\n--- a/one.go\n+++ b/one.go\n" +
		"@@ -1,3 +1,3 @@ func first()\n //nolint:all\n-// Code generated by a tool. DO NOT EDIT.\n" +
		"+package main\n //nolint:funlen\n" +
		"@@ -8 +8,2 @@\n-old\n+text\n+//nolint\n" +
		`diff --git "a/::notice::\303\251\nx.go" "b/::notice::\303\251\nx.go"` + "\nnew file mode 100644\n" +
		"--- /dev/null\n" + `+++ "b/::notice::\303\251\nx.go"` + "\n@@ -0,0 +1 @@\n" +
		"+//nolint:funlen\n\\ No newline at end of file\n" +
		"diff --git a/with space.go b/with space.go\n--- a/with space.go\t\n+++ b/with space.go\t\n" +
		"@@ -3 +3 @@\n-old\n+//nolint:all\n"
	const want = "\"::notice::\u00e9\\nx.go\" 1: " + funlen + "\n" +
		`"one.go" 9: ` + bare + "\n" +
		`"with space.go" 3: ` + all + "\nLint directives failed. Violations: 3.\n"
	root := t.TempDir()
	fixtureFile(
		t,
		root,
		"one.go",
		"//nolint:all\n"+sourcePkg+"//nolint:funlen\n\n\n\n\n\nvar x = 0 //nolint\n",
	)
	fixtureFile(t, root, "::notice::\u00e9\nx.go", "//nolint:funlen\n"+sourcePkg)
	fixtureFile(t, root, "with space.go", sourcePkg+"\n//nolint:all\n")
	assertDirectives(
		t,
		directiveTest{args: []string{rootFlag, root, guardFlag}, diff: patch},
		want,
		1,
	)
}

func TestDirectiveIgnoresNonAddedCommentsAndStrings(t *testing.T) {
	t.Parallel()
	for _, tc := range []struct{ name, source, hunk string }{
		{"unchanged header", "// Code generated by a tool. DO NOT EDIT.\n" + sourcePkg, "@@ -2 +2 @@\n-old\n+new\n"},
		{"raw string", sourcePkg + "const value = `\n//nolint:funlen\n`\n", "@@ -2,0 +3 @@\n+//nolint:funlen\n"},
		{"after declarations", sourcePkg + "var x int\n// autogenerated file\n", "@@ -2,0 +3 @@\n+comment\n"},
		{"go generate directive", "//go:generate echo code generated\n" + sourcePkg, "@@ -0,0 +1 @@\n+comment\n"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			root := t.TempDir()
			fixtureFile(t, root, "new.go", tc.source)
			args := []string{rootFlag, root, guardFlag}
			diff := "--- a/new.go\n+++ b/new.go\n" + tc.hunk
			assertDirectives(t, directiveTest{args: args, diff: diff}, passed, 0)
		})
	}
}

func TestDirectiveErrors(t *testing.T) {
	t.Parallel()
	for _, tc := range []struct {
		name string
		directiveTest
	}{
		{name: "missing guarded"},
		{name: "positional argument", directiveTest: directiveTest{args: []string{"--guarded=", "extra"}}},
		{
			name: "malformed hunk",
			directiveTest: directiveTest{
				args: []string{guardFlag},
				diff: "--- a/old.go\n+++ b/old.go\n@@ -1 +bogus @@\n+//nolint\n",
			},
		},
		{
			name: "truncated hunk",
			directiveTest: directiveTest{
				args: []string{guardFlag},
				diff: "--- /dev/null\n+++ b/new.go\n@@ -0,0 +1,2 @@\n+//nolint\n",
			},
		},
		{
			name:          "unexpected text",
			directiveTest: directiveTest{args: []string{"--guarded="}, diff: "::warning::not a diff\n"},
		},
	} {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			args := append([]string{rootFlag, t.TempDir()}, tc.args...)
			assertDirectives(t, directiveTest{args: args, diff: tc.diff}, "", 2)
		})
	}
}

func TestDirectiveSourceErrors(t *testing.T) {
	t.Parallel()
	root := t.TempDir()
	args := []string{rootFlag, root, guardFlag}
	diff := addedHunk + "+contents\n"
	bad := fixtureFile(t, root, "bad.go", sourcePkg+"func\n")
	link := filepath.Join(root, "new.go")
	if err := os.Symlink(bad, link); err != nil {
		t.Fatal(err)
	}
	assertDirectiveError(
		t,
		directiveTest{args: args, diff: diff},
		`"new.go": expected a readable regular source`,
	)
	assertDirectiveError(
		t,
		directiveTest{args: args, diff: strings.ReplaceAll(diff, "new.go", "bad.go")},
		`"bad.go": parse source`,
	)
	assertDirectiveError(t, directiveTest{args: []string{guardFlag}}, "expected --root")
}

func assertDirectiveError(t *testing.T, input directiveTest, want string) {
	t.Helper()
	var stdout, stderr bytes.Buffer
	code := executeDirectives(input.args, strings.NewReader(input.diff), &stdout, &stderr)
	if code != 2 || stdout.Len() != 0 || !strings.Contains(stderr.String(), want) {
		t.Fatalf(
			"code = %d, stdout = %q, stderr = %q; want exit 2 and error %q",
			code,
			&stdout,
			&stderr,
			want,
		)
	}
}

type directiveTest struct {
	args []string
	diff string
}

func assertDirectives(t *testing.T, input directiveTest, want string, wantCode int) {
	t.Helper()
	var stdout, stderr bytes.Buffer
	code := executeDirectives(input.args, strings.NewReader(input.diff), &stdout, &stderr)
	validError := (wantCode == 2 && strings.HasPrefix(stderr.String(), "lint-baseline: ")) ||
		(wantCode != 2 && stderr.Len() == 0)
	if code != wantCode || stdout.String() != want || !validError {
		t.Fatalf("code = %d, stdout = %q, stderr = %q; want code %d and stdout %q",
			code, stdout.String(), stderr.String(), wantCode, want)
	}
}
