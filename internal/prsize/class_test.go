package prsize

import (
	"strings"
	"testing"
)

func TestClassify(t *testing.T) {
	t.Parallel()

	const marker = "// Code generated by a tool. DO NOT EDIT."
	const clause = "\npackage sample\n"
	const goFile = "code.go"
	cases := []struct {
		name    string
		path    string
		content string
		want    class
	}{
		{"header before tests and docs", "docs/code_test.go", marker + clause, generated},
		{"non-Go source with header", "script.ts", marker + "\nconst x = 1\n", production},
		{"Go header after package", goFile, clause + marker + "\n", production},
		{"header on line 40", goFile, strings.Repeat("\n", 39) + marker + "\r" + clause, generated},
		{
			"header after long preamble",
			goFile,
			strings.Repeat("// license\n", 200) + marker + clause,
			generated,
		},
		{"unanchored header", goFile, " " + marker + clause, production},
		{"header inside block comment", goFile, "/*\n" + marker + "\n*/" + clause, production},
		{"protobuf", "pkg/code.pb.go", "", generated},
		{"locks", "nested/package-lock.json", "", generated},
		{"Go sums", "go.sum", "", generated},
		{"mise lock", "mise.lock", "", generated},
		{"generated docs", "CHANGELOG.md", "", generated},
		{"third-party licenses", "THIRD_PARTY_LICENSES.md", "", generated},
		{"Go tests", "docs/code_test.go", "", tests},
		{"TypeScript tests", "desktop/src/window.test.ts", "", tests},
		{"test directory", ".github/test/a.yml", "", tests},
		{"JavaScript test directory", "pkg/__tests__/helper.js", "", tests},
		{"end-to-end test directory", "e2e/README.md", "", tests},
		{"fixture", "pkg/testdata/output.json", "", tests},
		{"test package", "pkg/test/helper.go", "", tests},
		{"file named test", "pkg/test", "", production},
		{"markdown before config", ".github/guide.mdx", "", docs},
		{"docs at root", "docs/logo.svg", "", docs},
		{"sites at root", "sites/page.html", "", docs},
		{"nested docs", "pkg/docs/data.json", "", production},
		{"workflow", ".github/workflows/build.yml", "", config},
		{"lint config", ".golangci.yaml", "", config},
		{"lint config alias", ".golangci.yml", "", config},
		{"lint config prefix", ".golangci", "", config},
		{"lint config case", ".GolangCI", "", production},
		{"chart config", "charts/app/values.yaml", "", config},
		{"deploy config", "deploy/app/values.toml", "", config},
		{"hack JSON", "hack/config.json", "", config},
		{"hack script", "hack/install.go", "", production},
		{"root config", "package.json", "", config},
		{"package data", "pkg/example.yaml", "", production},
		{"desktop data", "desktop/src/example.json", "", production},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			if got := classify(tc.path, tc.content); got != tc.want {
				t.Errorf("classify(%q) = %v, want %v", tc.path, got, tc.want)
			}
		})
	}
}
