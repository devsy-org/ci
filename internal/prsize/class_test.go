package prsize

import (
	"strings"
	"testing"
)

func TestClassify(t *testing.T) {
	t.Parallel()

	const marker = "// Code generated by a tool. DO NOT EDIT."
	const script = "script.ts"
	cases := []struct {
		name    string
		path    string
		content string
		want    class
	}{
		{"header before tests and docs", "e2e/docs.md", marker, generated},
		{"header on line 40", script, strings.Repeat("\n", 39) + marker + "\r\n", generated},
		{"header on line 41", script, strings.Repeat("\n", 40) + marker, production},
		{"unanchored header", script, " " + marker, production},
		{"protobuf", "pkg/code.pb.go", "", generated},
		{"locks", "nested/package-lock.json", "", generated},
		{"generated docs", "CHANGELOG.md", "", generated},
		{"Go tests", "docs/code_test.go", "", tests},
		{"TypeScript tests", "desktop/src/window.test.ts", "", tests},
		{"test directory", ".github/test/a.yml", "", tests},
		{"fixture", "pkg/testdata/output.json", "", tests},
		{"markdown before config", ".github/guide.mdx", "", docs},
		{"docs at root", "docs/logo.svg", "", docs},
		{"sites at root", "sites/page.html", "", docs},
		{"nested docs", "pkg/docs/data.json", "", production},
		{"workflow", ".github/workflows/build.yml", "", config},
		{"lint config", ".golangci.yaml", "", config},
		{"chart config", "charts/app/values.yaml", "", config},
		{"deploy config", "deploy/app/values.toml", "", config},
		{"hack JSON", "hack/config.json", "", config},
		{"hack script", "hack/install.go", "", production},
		{"root config", "package.json", "", config},
		{"package data", "pkg/example.yaml", "", production},
		{"desktop data", "desktop/src/example.json", "", production},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			if got := classify(tc.path, tc.content); got != tc.want {
				t.Errorf("classify(%q) = %v, want %v", tc.path, got, tc.want)
			}
		})
	}
}
