func TestParseChange(t *testing.T) {
	t.Parallel()

	cases := []struct {
		name string
		raw  string
		want change
		bad  bool
	}{
		{
			name: "tab and newline in path",
			raw:  "2\t3\tfilename\twith\nspace.go\x00",
			want: change{"filename\twith\nspace.go", 5},
		},
		{name: "rename", raw: "1\t2\t\x00old.go\x00new.go\x00", want: change{"new.go", 3}},
		{name: "binary", raw: "-\t-\timage.png\x00", want: change{"image.png", 0}},
		{name: "incomplete header", raw: "1\t2\x00", bad: true},
		{name: "incomplete rename", raw: "1\t2\t\x00old.go\x00", bad: true},
		{name: "invalid count", raw: "a\t2\tfile.go\x00", bad: true},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			raw := tc.raw
			if !tc.bad {
				raw += "1\t0\tnext.go\x00"
			}
			got, remaining, err := parseChange(diffFields(raw))
			if (err != nil) != tc.bad {
				t.Fatalf("parseChange error = %v, want error: %t", err, tc.bad)
			}
			if !tc.bad &&
				(got != tc.want || !reflect.DeepEqual(remaining, []string{"1\t0\tnext.go"})) {
				t.Errorf("parseChange = %+v, %q; want %+v and next record", got, remaining, tc.want)
			}
		})
	}
}

func TestParseStatus(t *testing.T) {
	t.Parallel()

	cases := []struct {
		name string
		raw  string
		want map[string]string
		bad  bool
	}{
		{
			name: "mixed", raw: "D\x00gone\t.go\x00R100\x00old.go\x00new\n.go\x00A\x00new.go\x00",
			want: map[string]string{"gone\t.go": "D", "new\n.go": "R100", "new.go": "A"},
		},
		{name: "missing path", raw: "D\x00", bad: true},
		{name: "missing destination", raw: "R100\x00old.go\x00", bad: true},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			got, err := parseStatus(tc.raw)
			if (err != nil) != tc.bad || !reflect.DeepEqual(got, tc.want) {
				t.Errorf("parseStatus = %v, %v; want %v, error: %t", got, err, tc.want, tc.bad)
			}
		})
	}
}

func TestInspectMissingBase(t *testing.T) {
	t.Parallel()

	missing := errors.New("no such ref")
	_, err := inspect(func(args ...string) (string, error) {
		if !reflect.DeepEqual(args, []string{"merge-base", "origin/main", "HEAD"}) {
			t.Fatalf("unexpected Git arguments: %q", args)
		}
		return "", missing
	}, "main")
	if !errors.Is(err, missing) || !strings.Contains(err.Error(), "origin/main") {
		t.Errorf("inspect = %v, want missing origin/main error", err)
	}
}

func TestInspectGitRepo(t *testing.T) {
	t.Parallel()
	if _, err := exec.LookPath("git"); err != nil {
		t.Skip("git is unavailable")
	}
	dir := t.TempDir()
	git := gitRunner(t.Context(), dir)
	gitOK(t, git, "init", "-b", "main")
	writeFixture(t, dir, "old.go", "a unique line to move\n")
	writeFixture(t, dir, "delete.go", "a unique line to remove\n")
	writeFixture(t, dir, "edit.go", "old\n")
	gitOK(t, git, "add", ".")
	base := commitFixture(t, git, "")
	gitOK(t, git, "update-ref", "refs/remotes/origin/main", "HEAD")
	gitOK(t, git, "mv", "old.go", "new.go")
	gitOK(t, git, "rm", "delete.go")
	writeFixture(t, dir, "edit.go", "replacement\nanother\n")
	writeFixture(t, dir, "binary.png", "\x00\x01\x02")
	writeFixture(
		t,
		dir,
		"generated.go",
		"package sample\n// Code generated by a tool. DO NOT EDIT.\n",
	)
	writeFixture(t, dir, "sample_test.go", "package sample\n")
	gitOK(t, git, "add", ".")
	gitOK(t, git, "update-index", "--add", "--cacheinfo", "160000,"+base+",submodule")
	commitFixture(t, git, base)
	writeFixture(t, dir, "generated.go", "working tree is ignored\n")

	got, err := inspect(git, "main")
	if err != nil {
		t.Fatal(err)
	}
	want := totals{
		generated:  {files: 1, lines: 2},
		tests:      {files: 1, lines: 1},
		production: {files: 5, lines: 4},
	}
	if got != want {
		t.Errorf("inspect = %+v, want %+v", got, want)
	}
}

func gitOK(t *testing.T, git gitFunc, args ...string) {
	t.Helper()
	gitOutput(t, git, args...)
}

func gitOutput(t *testing.T, git gitFunc, args ...string) string {
	t.Helper()
	out, err := git(args...)
	if err != nil {
		t.Fatalf("git %q: %v", args, err)
	}
	return strings.TrimSpace(out)
}

func commitFixture(t *testing.T, git gitFunc, parent string) string {
	t.Helper()
	tree := gitOutput(t, git, "write-tree")
	commit := "tree " + tree + "\n"
	if parent != "" {
		commit += "parent " + parent + "\n"
	}
	const stamp = "Fixture <fixture@example.invalid> 1 +0000"
	commit += fmt.Sprintf("author %s\ncommitter %s\n\nTest snapshot\n", stamp, stamp)
	dir := t.TempDir()
	writeFixture(t, dir, "commit", commit)
	hash := gitOutput(t, git, "hash-object", "-w", "-t", "commit", filepath.Join(dir, "commit"))
	gitOK(t, git, "update-ref", "HEAD", hash)
	return hash
}

func writeFixture(t *testing.T, dir, name, contents string) {
	t.Helper()
	if err := os.WriteFile(filepath.Join(dir, name), []byte(contents), 0o600); err != nil {
		t.Fatal(err)
	}
}
